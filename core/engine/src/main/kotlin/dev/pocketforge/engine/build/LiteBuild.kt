/**
 * "Android lite" projects: plain Android framework code (no AndroidX, no Gradle plugins needed),
 * described by `pocketforge.json`. They build three ways:
 *  1. with Gradle + AGP on a computer / Build Host (files are a normal Gradle project),
 *  2. with the direct toolchain script below (aapt2 → javac/kotlinc → d8 → apksigner),
 *     e.g. inside Termux on the phone (see TermuxProtocol), or on any Linux/macOS box,
 *  3. exported as a ZIP.
 */
data class LiteBuildDescriptor(
    val packageId: String,
    val minSdk: Int,
    val targetSdk: Int,
    val versionCode: Int,
    val versionName: String,
    val manifest: String,
    val res: String?,
    val assets: String?,
    val sources: List<String>,
) {
    companion object {
        const val FILE = "pocketforge.json"

        /** Parses and validates the descriptor. Every path must stay inside the project. */
        fun load(projectRoot: File): LiteBuildDescriptor {
            val f = File(projectRoot, FILE)
            if (!f.isFile) throw PfException("lite.no_descriptor", "This project has no $FILE, so the on-device toolchain cannot build it. Use Export or a Build Host.")
            val o = Json.parseObject(f.readText())
            if (o.str("type") != "android-lite") throw PfException("lite.bad_type", "$FILE is not an android-lite descriptor.")
            val guard = PathGuard(projectRoot)
            fun path(key: String, required: Boolean): String? {
                val v = o.str(key) ?: if (required) throw PfException("lite.missing_key", "$FILE is missing \"$key\".") else return null
                return guard.normalize(v)
            }
            val pkg = o.str("packageId") ?: throw PfException("lite.missing_key", "$FILE is missing \"packageId\".")
            PackageNames.validate(pkg)?.let { throw PfException("lite.bad_package", it) }
            val min = o.int("minSdk") ?: 26
            val target = o.int("targetSdk") ?: 35
            if (min !in 21..36 || target !in min..36) throw PfException("lite.bad_sdk", "minSdk must be 21–36 and targetSdk between minSdk and 36.")
            val vc = o.int("versionCode") ?: 1
            if (vc < 1) throw PfException("lite.bad_version", "versionCode must be 1 or higher.")
            val vn = (o.str("versionName") ?: "1.0").take(64)
            if (!vn.matches(Regex("[A-Za-z0-9._+\\- ]+"))) throw PfException("lite.bad_version", "versionName may only contain letters, digits, space and . _ + -")
            val sources = o.arr("sources").mapNotNull { (it as? JsonString)?.value }.map { guard.normalize(it) }
            if (sources.isEmpty()) throw PfException("lite.no_sources", "$FILE lists no source folders.")
            return LiteBuildDescriptor(pkg, min, target, vc, vn, path("manifest", true)!!, path("res", false), path("assets", false), sources)
        }
    }
}

object LiteBuildScript {
    const val RESULT_PREFIX = "PF_RESULT "
    const val OUTPUT_APK = "build/pocketforge/app-debug.apk"

    /** POSIX single-quote escaping. Values are also validated, so this is defence in depth. */
    private fun q(s: String) = "'" + s.replace("'", "'\\''") + "'"

    /**
     * Generates a bash script that builds a signed debug APK with tools already installed on the
     * machine. It never downloads or installs anything; missing tools are reported as PF_MISSING lines.
     */
    fun generate(d: LiteBuildDescriptor, generatorVersion: String): String = buildString {
        append("#!/usr/bin/env bash\n")
        append("# Generated by PocketForge $generatorVersion. Builds this android-lite project with tools that are\n")
        append("# ALREADY installed (e.g. Termux packages). It never downloads, installs or uploads anything.\n")
        append("set -euo pipefail\n")
        append("cd \"\$(dirname \"\$0\")/..\"\n")
        append("ROOT=\"\$(pwd)\"\nOUT=\"\$ROOT/build/pocketforge\"\n")
        append("PKG=${q(d.packageId)}\nMIN=${d.minSdk}\nTARGET=${d.targetSdk}\nVCODE=${d.versionCode}\nVNAME=${q(d.versionName)}\n")
        append("MANIFEST=${q(d.manifest)}\nRES=${q(d.res ?: "")}\nASSETS=${q(d.assets ?: "")}\n")
        append("SOURCES=(").append(d.sources.joinToString(" ") { q(it) }).append(")\n")
        append(
            """
trap 'code=${'$'}?; echo "PF_RESULT failed reason=step-failed exit=${'$'}code"; exit ${'$'}code' ERR
say() { printf 'PF_STEP %s\n' "${'$'}*"; }
have() { command -v "${'$'}1" >/dev/null 2>&1; }
missing=()
for t in aapt2 d8 apksigner keytool; do have "${'$'}t" || missing+=("${'$'}t"); done
JAVAC=""
if have javac; then JAVAC=javac; elif have ecj; then JAVAC=ecj; else missing+=("javac (openjdk-17) or ecj"); fi
ZIPPER=""
if have zip; then ZIPPER=zip; elif have jar; then ZIPPER=jar; else missing+=("zip"); fi
ANDROID_JAR="${'$'}{ANDROID_JAR:-}"
if [ -z "${'$'}ANDROID_JAR" ]; then
  for c in "${'$'}{PREFIX:-/nonexistent}/share/aapt/android.jar" "${'$'}{PREFIX:-/nonexistent}/share/java/android.jar" \
           "${'$'}HOME/android-sdk/platforms/android-${'$'}TARGET/android.jar" "${'$'}HOME/.pocketforge/android.jar"; do
    if [ -f "${'$'}c" ]; then ANDROID_JAR="${'$'}c"; break; fi
  done
fi
if [ -z "${'$'}ANDROID_JAR" ] || [ ! -f "${'$'}ANDROID_JAR" ]; then missing+=("android.jar (set ANDROID_JAR=/path/to/android.jar)"); fi
KT_COUNT=0
for s in "${'$'}{SOURCES[@]}"; do if [ -d "${'$'}s" ]; then KT_COUNT=${'$'}(( KT_COUNT + ${'$'}(find "${'$'}s" -name '*.kt' | wc -l) )); fi; done
if [ "${'$'}KT_COUNT" -gt 0 ] && ! have kotlinc; then missing+=("kotlinc (needed for .kt sources)"); fi
if [ ${'$'}{#missing[@]} -gt 0 ]; then
  for m in "${'$'}{missing[@]}"; do echo "PF_MISSING ${'$'}m"; done
  echo "PF_RESULT failed reason=missing-tools"
  trap - ERR; exit 3
fi
echo "PF_TOOL aapt2=${'$'}(command -v aapt2) d8=${'$'}(command -v d8) apksigner=${'$'}(command -v apksigner) javac=${'$'}JAVAC android.jar=${'$'}ANDROID_JAR"

rm -rf "${'$'}OUT"
mkdir -p "${'$'}OUT/res" "${'$'}OUT/gen" "${'$'}OUT/classes" "${'$'}OUT/dex"

say manifest
if grep -q 'package="' "${'$'}MANIFEST"; then cp "${'$'}MANIFEST" "${'$'}OUT/AndroidManifest.xml"
else sed '0,/<manifest/s//<manifest package="'"${'$'}PKG"'"/' "${'$'}MANIFEST" > "${'$'}OUT/AndroidManifest.xml"; fi

say resources
RESARG=()
if [ -n "${'$'}RES" ] && [ -d "${'$'}RES" ]; then aapt2 compile --dir "${'$'}RES" -o "${'$'}OUT/res/compiled.zip"; RESARG=("${'$'}OUT/res/compiled.zip"); fi
ASSETARG=()
if [ -n "${'$'}ASSETS" ] && [ -d "${'$'}ASSETS" ]; then ASSETARG=(-A "${'$'}ASSETS"); fi
aapt2 link -I "${'$'}ANDROID_JAR" --manifest "${'$'}OUT/AndroidManifest.xml" --debug-mode \
  --min-sdk-version "${'$'}MIN" --target-sdk-version "${'$'}TARGET" --version-code "${'$'}VCODE" --version-name "${'$'}VNAME" \
  --java "${'$'}OUT/gen" ${'$'}{ASSETARG[@]+"${'$'}{ASSETARG[@]}"} -o "${'$'}OUT/base.apk" ${'$'}{RESARG[@]+"${'$'}{RESARG[@]}"}

say compile
JAVA_LIST="${'$'}OUT/java-sources.txt"
: > "${'$'}JAVA_LIST"
for s in "${'$'}{SOURCES[@]}" "${'$'}OUT/gen"; do if [ -d "${'$'}s" ]; then find "${'$'}s" -name '*.java' >> "${'$'}JAVA_LIST"; fi; done
KSTDLIB=()
if [ "${'$'}KT_COUNT" -gt 0 ]; then
  KT_SRC=()
  for s in "${'$'}{SOURCES[@]}"; do if [ -d "${'$'}s" ]; then KT_SRC+=("${'$'}s"); fi; done
  kotlinc -no-jdk -no-reflect -jvm-target 1.8 -nowarn -cp "${'$'}ANDROID_JAR" -d "${'$'}OUT/classes" "${'$'}{KT_SRC[@]}" "${'$'}OUT/gen"
  KLIB="${'$'}(cd "${'$'}(dirname "${'$'}(readlink -f "${'$'}(command -v kotlinc)")")/../lib" && pwd)"
  KSTDLIB=("${'$'}KLIB/kotlin-stdlib.jar")
fi
if [ -s "${'$'}JAVA_LIST" ]; then
  if [ "${'$'}JAVAC" = javac ]; then
    # --release 8 supplies java.lang.invoke (lambdas) from the JDK's API signatures; android.* comes from android.jar.
    javac -nowarn -Xlint:-options --release 8 -encoding UTF-8 \
      -classpath "${'$'}ANDROID_JAR:${'$'}OUT/classes" -d "${'$'}OUT/classes" @"${'$'}JAVA_LIST"
  else
    ecj -8 -nowarn -encoding UTF-8 -bootclasspath "${'$'}ANDROID_JAR" -classpath "${'$'}OUT/classes" -d "${'$'}OUT/classes" @"${'$'}JAVA_LIST"
  fi
fi

say dex
CLASSES=()
while IFS= read -r -d '' f; do CLASSES+=("${'$'}f"); done < <(find "${'$'}OUT/classes" -name '*.class' -print0)
if [ ${'$'}{#CLASSES[@]} -eq 0 ]; then echo "PF_RESULT failed reason=no-classes"; trap - ERR; exit 5; fi
d8 --min-api "${'$'}MIN" --lib "${'$'}ANDROID_JAR" --output "${'$'}OUT/dex" "${'$'}{CLASSES[@]}" ${'$'}{KSTDLIB[@]+"${'$'}{KSTDLIB[@]}"}

say package
cp "${'$'}OUT/base.apk" "${'$'}OUT/unsigned.apk"
if [ "${'$'}ZIPPER" = zip ]; then (cd "${'$'}OUT/dex" && zip -q -X "${'$'}OUT/unsigned.apk" classes*.dex)
else (cd "${'$'}OUT/dex" && jar uMf "${'$'}OUT/unsigned.apk" classes*.dex); fi

say sign
KS="${'$'}{PF_DEBUG_KEYSTORE:-${'$'}HOME/.pocketforge/debug.keystore}"
if [ ! -f "${'$'}KS" ]; then
  mkdir -p "${'$'}(dirname "${'$'}KS")"
  keytool -genkeypair -keystore "${'$'}KS" -storetype PKCS12 -storepass android -keypass android -alias androiddebugkey \
    -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=Android Debug,O=Android,C=US" >/dev/null 2>&1
  echo "PF_NOTE created debug keystore ${'$'}KS (debug key: do not use for releases)"
fi
apksigner sign --ks "${'$'}KS" --ks-pass pass:android --key-pass pass:android --ks-key-alias androiddebugkey \
  --out "${'$'}OUT/app-debug.apk" "${'$'}OUT/unsigned.apk"
apksigner verify "${'$'}OUT/app-debug.apk"
SHA="${'$'}( (sha256sum "${'$'}OUT/app-debug.apk" 2>/dev/null || shasum -a 256 "${'$'}OUT/app-debug.apk") | cut -d' ' -f1)"
trap - ERR
echo "PF_RESULT ok apk=$OUTPUT_APK sha256=${'$'}SHA"
""".trimStart(),
        )
    }

    data class ParsedOutput(val ok: Boolean, val reason: String?, val apkPath: String?, val sha256: String?, val missing: List<String>, val steps: List<String>)

    /** Parses PF_* marker lines. The app still re-hashes and inspects the APK itself before reporting success. */
    fun parse(output: String): ParsedOutput {
        val lines = output.lines()
        val result = lines.lastOrNull { it.startsWith(RESULT_PREFIX) }
        val fields = result?.removePrefix(RESULT_PREFIX)?.split(' ')?.drop(1)?.mapNotNull { kv ->
            val i = kv.indexOf('='); if (i <= 0) null else kv.substring(0, i) to kv.substring(i + 1)
        }?.toMap() ?: emptyMap()
        return ParsedOutput(
            ok = result?.removePrefix(RESULT_PREFIX)?.startsWith("ok") == true,
            reason = fields["reason"],
            apkPath = fields["apk"],
            sha256 = fields["sha256"]?.lowercase()?.takeIf { it.matches(Regex("[0-9a-f]{64}")) },
            missing = lines.filter { it.startsWith("PF_MISSING ") }.map { it.removePrefix("PF_MISSING ") },
            steps = lines.filter { it.startsWith("PF_STEP ") }.map { it.removePrefix("PF_STEP ") },
        )
    }
}

/** Plain-framework Android app (Java). Builds on desktop with Gradle and on the phone with the lite toolchain. */
object AndroidLiteTemplate : ProjectTemplate {
    override val id = "android-lite"
    override val title = "Android app — lightweight (Java, no libraries)"
    override val description = "Uses only the Android framework, so it can be built on this phone through Termux, on a Build Host, or in Android Studio."
    override val language = "Java"
    override val needsPackageId = true
    override val prerequisites = listOf(
        "On the phone: Termux with packages aapt2, d8, apksigner, openjdk-17 and an android.jar (see Help → On-device builds)",
        "Or on a computer: JDK 17+, Android SDK Platform 35, Gradle 8.14+ (`gradle wrapper`, then `./gradlew assembleDebug`)",
    )

    override fun files(input: TemplateInput): Map<String, String> {
        val pkg = input.packageId
        val pkgPath = pkg.replace('.', '/')
        val m = Templates.common(input, this, "## Build\n\nOn the phone: PocketForge → Build Center → *On-device (Termux)*.\n\nOn a computer:\n\n```\ngradle wrapper\n./gradlew assembleDebug\n```\n").toMutableMap()
        m[".gitignore"] = "build/\n.gradle/\n/local.properties\n.idea/\n*.iml\n*.jks\n*.keystore\n"
        m[LiteBuildDescriptor.FILE] = Json.stringify(
            Json.obj(
                "schema" to 1, "type" to "android-lite", "packageId" to pkg, "minSdk" to input.minSdk, "targetSdk" to 35,
                "versionCode" to 1, "versionName" to "1.0", "manifest" to "app/src/main/AndroidManifest.xml",
                "res" to "app/src/main/res", "assets" to "app/src/main/assets", "sources" to listOf("app/src/main/java"),
            ),
            pretty = true,
        ) + "\n"
        m["settings.gradle.kts"] = "pluginManagement {\n    repositories {\n        google()\n        mavenCentral()\n        gradlePluginPortal()\n    }\n}\ndependencyResolutionManagement {\n    repositories {\n        google()\n        mavenCentral()\n    }\n}\nrootProject.name = \"${input.name.replace("\"", "")}\"\ninclude(\":app\")\n"
        m["build.gradle.kts"] = "plugins {\n    id(\"com.android.application\") version \"8.13.0\" apply false\n}\n"
        m["app/build.gradle.kts"] = """plugins {
    id("com.android.application")
}

android {
    namespace = "$pkg"
    compileSdk = 35

    defaultConfig {
        applicationId = "$pkg"
        minSdk = ${input.minSdk}
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
}

dependencies {
    testImplementation("junit:junit:4.13.2")
}
"""
        m["app/src/main/AndroidManifest.xml"] = """<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <application
        android:allowBackup="false"
        android:label="@string/app_name"
        android:theme="@android:style/Theme.Material.Light.NoActionBar">
        <activity
            android:name=".MainActivity"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity>
    </application>
</manifest>
"""
        m["app/src/main/res/values/strings.xml"] = """<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="app_name">${xmlText(input.name)}</string>
    <string name="greeting">Hello from ${xmlText(input.name)}!</string>
</resources>
"""
        m["app/src/main/assets/README.txt"] = "Files in this folder are packaged into the APK unchanged.\n"
        m["app/src/main/java/$pkgPath/Greeter.java"] = """package $pkg;

/** Pure logic, kept separate from the UI so it can be unit-tested anywhere. */
public final class Greeter {
    private Greeter() {}

    public static String label(int count) {
        return count == 1 ? "Tapped 1 time" : "Tapped " + count + " times";
    }
}
"""
        m["app/src/main/java/$pkgPath/MainActivity.java"] = """package $pkg;

import android.app.Activity;
import android.os.Bundle;
import android.view.Gravity;
import android.widget.Button;
import android.widget.LinearLayout;
import android.widget.TextView;

public class MainActivity extends Activity {
    private int count = 0;
    private Button button;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        if (savedInstanceState != null) count = savedInstanceState.getInt("count", 0);

        int pad = (int) (24 * getResources().getDisplayMetrics().density);
        LinearLayout root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setGravity(Gravity.CENTER);
        root.setPadding(pad, pad, pad, pad);
        root.setFitsSystemWindows(true);

        TextView title = new TextView(this);
        title.setText(R.string.greeting);
        title.setTextSize(24);
        title.setGravity(Gravity.CENTER);
        root.addView(title);

        button = new Button(this);
        button.setText(Greeter.label(count));
        button.setOnClickListener(v -> {
            count++;
            button.setText(Greeter.label(count));
        });
        root.addView(button);

        setContentView(root);
    }

    @Override
    protected void onSaveInstanceState(Bundle outState) {
        super.onSaveInstanceState(outState);
        outState.putInt("count", count);
    }
}
"""
        m["app/src/test/java/$pkgPath/GreeterTest.java"] = """package $pkg;

import static org.junit.Assert.assertEquals;

import org.junit.Test;

public class GreeterTest {
    @Test
    public void singular() {
        assertEquals("Tapped 1 time", Greeter.label(1));
    }

    @Test
    public void plural() {
        assertEquals("Tapped 3 times", Greeter.label(3));
    }
}
"""
        return m
    }

    private fun xmlText(s: String) = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'").replace("\"", "\\\"")
}
