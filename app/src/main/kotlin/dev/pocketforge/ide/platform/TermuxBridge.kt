/**
 * EXPERIMENTAL on-device build/test bridge to Termux (installed and set up by the user).
 *
 * Flow: copy the manifest-filtered project into a shared folder the user picked with Android's
 * folder picker → write .pocketforge/build.sh (generated, reviewed in-app) → ask Termux to run it via
 * its documented RUN_COMMAND intent → Termux returns stdout/stderr/exit code to our PendingIntent →
 * we read the APK back through the same folder grant, re-hash and inspect it, and only then record SUCCESS.
 * No network is used by PocketForge here; what Termux does is governed by Termux's own permissions.
 */
class TermuxBridge(private val c: AppContainer) {
    enum class Kind { BUILD, TEST }

    data class Pending(val token: String, val projectId: String, val kind: Kind, val command: String, val folderName: String, val startedAt: Long)

    @Volatile var pending: Pending? = null
        private set

    private val listeners = CopyOnWriteArrayList<(BuildAttempt) -> Unit>()
    fun addListener(l: (BuildAttempt) -> Unit) { listeners += l }
    fun removeListener(l: (BuildAttempt) -> Unit) { listeners -= l }

    private val ctx: Context get() = c.app

    fun isInstalled() = c.probe.termuxInstalled()
    fun hasPermission() = ctx.checkSelfPermission(TermuxProtocol.PERMISSION) == PackageManager.PERMISSION_GRANTED

    fun treeUri(): Uri? = c.settings.value.termuxTreeUri.takeIf { it.isNotBlank() }?.let(Uri::parse)
        ?.takeIf { u -> ctx.contentResolver.persistedUriPermissions.any { it.uri == u && it.isReadPermission && it.isWritePermission } }

    /** The exact script that would run, so the user can read it before approving. */
    fun buildScriptFor(projectRoot: File): String = LiteBuildScript.generate(LiteBuildDescriptor.load(projectRoot), BuildInfo.VERSION_NAME)

    fun testScriptFor(command: String): String {
        require(command.isNotBlank() && command.length <= 1000 && command.none { it == '\u0000' || it == '\n' || it == '\r' }) { "invalid command" }
        return "#!/usr/bin/env bash\n# Generated by PocketForge ${BuildInfo.VERSION_NAME}: runs the test command you approved.\ncd \"\$(dirname \"\$0\")/..\"\n$command\n"
    }

    /**
     * Copies the project (and the script) into <tree>/<folderName>/ and starts it in Termux.
     * Blocking; call from a background thread. Throws [PfException] with an actionable message.
     */
    fun start(projectId: String, projectName: String, kind: Kind, script: String, command: String) {
        if (pending != null) throw PfException("termux.busy", "A Termux run is already in progress. Wait for it or choose Stop waiting.")
        if (!isInstalled()) throw PfException("termux.missing", "Termux is not installed.")
        if (!hasPermission()) throw PfException("termux.permission", "PocketForge does not have Termux's \"Run commands in Termux environment\" permission yet.")
        val tree = treeUri() ?: throw PfException("termux.no_folder", "Choose the shared build folder first (and keep its access granted).")
        val base = c.settings.value.termuxPath.trimEnd('/')
        TermuxProtocol.validateWorkspacePath(base)?.let { throw PfException("termux.bad_path", it) }
        val root = c.projects.dirOf(projectId)
        val folderName = TermuxProtocol.projectFolderName(projectName, projectId)
        val scriptName = if (kind == Kind.BUILD) "build.sh" else "test.sh"
        syncProject(tree, folderName, root, mapOf(".pocketforge/$scriptName" to script.toByteArray()))

        val token = ByteArray(16).also(SecureRandom()::nextBytes).joinToString("") { "%02x".format(it) }
        val cb = Intent(ctx, TermuxResultReceiver::class.java).setAction(TermuxResultReceiver.ACTION).putExtra(TermuxResultReceiver.EXTRA_TOKEN, token)
        val pi = PendingIntent.getBroadcast(ctx, 4711, cb, PendingIntent.FLAG_UPDATE_CURRENT or Compat.mutableFlag())
        val projectPath = "$base/$folderName"
        val run = Intent(TermuxProtocol.ACTION)
            .setClassName(TermuxProtocol.PACKAGE, TermuxProtocol.SERVICE)
            .putExtra(TermuxProtocol.EXTRA_PATH, TermuxProtocol.BASH)
            .putExtra(TermuxProtocol.EXTRA_ARGUMENTS, arrayOf("$projectPath/.pocketforge/$scriptName"))
            .putExtra(TermuxProtocol.EXTRA_WORKDIR, projectPath)
            .putExtra(TermuxProtocol.EXTRA_BACKGROUND, true)
            .putExtra(TermuxProtocol.EXTRA_PENDING_INTENT, pi)
        pending = Pending(token, projectId, kind, command, folderName, System.currentTimeMillis())
        try {
            ctx.startForegroundService(run)
        } catch (e: Exception) {
            pending = null
            throw PfException("termux.start_failed", "Termux refused the request: ${e.message}. In Termux, add allow-external-apps=true to ~/.termux/termux.properties and restart Termux.")
        }
        c.log.info("termux", "started ${kind.name.lowercase()} for project ${projectId.take(8)}")
    }

    /** Stops waiting in the UI. If Termux still reports back later, the result is recorded honestly. */
    fun stopWaiting() { pending = pending?.copy(token = "late:" + (pending?.token ?: "")) }

    /** Called by [TermuxResultReceiver] on a background thread. */
    internal fun onResult(token: String?, stdout: String, stderr: String, exitCode: Int?, err: Int, errmsg: String?) {
        val p = pending ?: run { c.log.warn("termux", "result without a pending run ignored"); return }
        if (token == null || (token != p.token && "late:$token" != p.token)) { c.log.warn("termux", "result with unknown token ignored"); return }
        pending = null
        val output = buildString {
            append(stdout)
            if (stderr.isNotBlank()) append("\n--- stderr ---\n").append(stderr)
            if (err != -1 && err != 0) append("\n--- Termux error $err: ${errmsg ?: ""} ---\n")
        }
        val hint = if (exitCode == 127 || stderr.contains("No such file or directory")) "\nPF_HINT The Termux path setting may not match the folder you picked, or termux-setup-storage was not run.\n" else ""
        val attempt = try {
            when (p.kind) {
                Kind.BUILD -> {
                    val apk = if (exitCode == 0) copyBackApk(p.folderName) else null
                    c.builds.recordToolchainBuild(p.projectId, "termux", p.startedAt, output + hint, exitCode, apk).also { apk?.delete() }
                }
                Kind.TEST -> c.builds.recordTestRun(p.projectId, "termux", p.command, p.startedAt, output + hint, exitCode)
            }
        } catch (e: Exception) {
            c.builds.recordTestRun(p.projectId, "termux", "result handling", p.startedAt, output + "\n" + (e.message ?: ""), null)
        }
        c.log.info("termux", "${p.kind} -> ${attempt.status}")
        c.main.post { listeners.forEach { runCatching { it(attempt) } } }
    }

    // ---- Storage Access Framework helpers (never assume a SAF URI is a file path) ----

    private fun syncProject(tree: Uri, folderName: String, root: File, extras: Map<String, ByteArray>) {
        val cr = ctx.contentResolver
        val treeDoc = DocumentsContract.buildDocumentUriUsingTree(tree, DocumentsContract.getTreeDocumentId(tree))
        findChild(cr, tree, treeDoc, folderName)?.let { DocumentsContract.deleteDocument(cr, it) }
        val projectDoc = createDir(cr, treeDoc, folderName)
        val dirs = HashMap<String, Uri>().apply { put("", projectDoc) }
        fun dirFor(rel: String): Uri {
            if (rel.isEmpty()) return projectDoc
            dirs[rel]?.let { return it }
            val parent = dirFor(rel.substringBeforeLast('/', ""))
            return createDir(cr, parent, rel.substringAfterLast('/')).also { dirs[rel] = it }
        }
        val included = ExportManifest.build(root).filter { it.include }
        if (included.size > 5000) throw PfException("termux.too_many", "Project has ${included.size} files; the Termux bridge copies at most 5000.")
        for (e in included) writeFile(cr, dirFor(e.path.substringBeforeLast('/', "")), e.path.substringAfterLast('/')) { out -> File(root, e.path).inputStream().use { it.copyTo(out) } }
        for ((path, bytes) in extras) writeFile(cr, dirFor(path.substringBeforeLast('/', "")), path.substringAfterLast('/')) { it.write(bytes) }
    }

    private fun createDir(cr: ContentResolver, parent: Uri, name: String): Uri =
        DocumentsContract.createDocument(cr, parent, DocumentsContract.Document.MIME_TYPE_DIR, name)
            ?: throw PfException("termux.saf", "Could not create folder $name in the shared build folder.")

    private fun writeFile(cr: ContentResolver, dir: Uri, name: String, write: (java.io.OutputStream) -> Unit) {
        val doc = DocumentsContract.createDocument(cr, dir, "application/octet-stream", name)
            ?: throw PfException("termux.saf", "Could not create $name in the shared build folder.")
        val shownName = cr.query(doc, arrayOf(DocumentsContract.Document.COLUMN_DISPLAY_NAME), null, null, null)?.use { if (it.moveToFirst()) it.getString(0) else null }
        if (shownName != null && shownName != name) throw PfException("termux.saf_renamed", "The storage provider renamed $name to $shownName; pick a folder on internal shared storage instead.")
        (cr.openOutputStream(doc, "w") ?: throw PfException("termux.saf", "Could not write $name.")).use(write)
    }

    private fun findChild(cr: ContentResolver, tree: Uri, parentDoc: Uri, name: String): Uri? {
        val children = DocumentsContract.buildChildDocumentsUriUsingTree(tree, DocumentsContract.getDocumentId(parentDoc))
        cr.query(children, arrayOf(DocumentsContract.Document.COLUMN_DOCUMENT_ID, DocumentsContract.Document.COLUMN_DISPLAY_NAME), null, null, null)?.use { cur ->
            while (cur.moveToNext()) if (cur.getString(1) == name) return DocumentsContract.buildDocumentUriUsingTree(tree, cur.getString(0))
        }
        return null
    }

    private fun copyBackApk(folderName: String): File? {
        val tree = treeUri() ?: return null
        val cr = ctx.contentResolver
        var cur: Uri = DocumentsContract.buildDocumentUriUsingTree(tree, DocumentsContract.getTreeDocumentId(tree))
        for (seg in listOf(folderName) + LiteBuildScript.OUTPUT_APK.split('/')) cur = findChild(cr, tree, cur, seg) ?: return null
        val out = File(ctx.cacheDir, "termux-apk/app-debug.apk").apply { parentFile?.mkdirs() }
        cr.openInputStream(cur)?.use { i -> out.outputStream().use { o ->
            val buf = ByteArray(64 * 1024); var total = 0L
            while (true) { val n = i.read(buf); if (n < 0) break; total += n; if (total > 512L * 1024 * 1024) throw PfException("termux.apk_too_large", "APK is larger than 512 MB."); o.write(buf, 0, n) }
        } } ?: return null
        return out
    }
}

/** Receives Termux's RUN_COMMAND result. Not exported: only Termux, holding our PendingIntent, can deliver it. */
class TermuxResultReceiver : BroadcastReceiver() {
    override fun onReceive(context: Context, intent: Intent) {
        if (intent.action != ACTION) return
        val c = PocketForgeApp.of(context)
        val bundle = intent.getBundleExtra(TermuxProtocol.RESULT_BUNDLE)
        val token = intent.getStringExtra(EXTRA_TOKEN)
        val stdout = bundle?.getString(TermuxProtocol.RESULT_STDOUT).orEmpty()
        val stderr = bundle?.getString(TermuxProtocol.RESULT_STDERR).orEmpty()
        val exit = bundle?.takeIf { it.containsKey(TermuxProtocol.RESULT_EXIT_CODE) }?.getInt(TermuxProtocol.RESULT_EXIT_CODE)
        val err = bundle?.getInt(TermuxProtocol.RESULT_ERR, -1) ?: -1
        val errmsg = bundle?.getString(TermuxProtocol.RESULT_ERRMSG)
        val async = goAsync()
        c.io.execute {
            try { c.termux.onResult(token, stdout, stderr, exit, err, errmsg) } finally { async.finish() }
        }
    }

    companion object {
        const val ACTION = "dev.pocketforge.ide.TERMUX_RESULT"
        const val EXTRA_TOKEN = "dev.pocketforge.ide.TOKEN"
    }
}
